-- ============================================================
-- 1. EXTENSIONS
-- ============================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto;


-- ============================================================
-- 2. PROFILES
-- Menyimpan profil pengguna dan role user/admin.
-- ============================================================

CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    full_name TEXT,
    role TEXT NOT NULL DEFAULT 'user'
        CHECK (role IN ('user', 'admin')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- ============================================================
-- 3. REPORTS
-- Menyimpan laporan pelanggaran lalu lintas.
-- ============================================================

CREATE TABLE IF NOT EXISTS public.reports (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    user_id UUID NOT NULL
        REFERENCES public.profiles(id) ON DELETE RESTRICT,

    category TEXT NOT NULL,
    description TEXT NOT NULL
        CHECK (char_length(description) BETWEEN 20 AND 3000),

    location TEXT NOT NULL
        CHECK (char_length(location) BETWEEN 3 AND 300),

    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,

    incident_time TIMESTAMPTZ,
    photo_path TEXT,

    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (
            status IN (
                'pending',
                'reviewing',
                'revision',
                'rejected',
                'forwarded',
                'in_progress',
                'completed'
            )
        ),

    admin_note TEXT,

    reviewed_by UUID
        REFERENCES public.profiles(id) ON DELETE SET NULL,

    reviewed_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT reports_latitude_range
        CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),

    CONSTRAINT reports_longitude_range
        CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),

    CONSTRAINT reports_coordinate_pair
        CHECK (
            (latitude IS NULL AND longitude IS NULL)
            OR
            (latitude IS NOT NULL AND longitude IS NOT NULL)
        )
);


-- ============================================================
-- 4. REPORT STATUS HISTORY
-- Mencatat perubahan status laporan.
-- ============================================================

CREATE TABLE IF NOT EXISTS public.report_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    report_id UUID NOT NULL
        REFERENCES public.reports(id) ON DELETE CASCADE,

    changed_by UUID
        REFERENCES public.profiles(id) ON DELETE SET NULL,

    old_status TEXT,
    new_status TEXT NOT NULL,
    note TEXT,

    changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- ============================================================
-- 5. INDEXES
-- Membantu pencarian dan pengambilan data.
-- ============================================================

CREATE INDEX IF NOT EXISTS idx_reports_user_id
    ON public.reports(user_id);

CREATE INDEX IF NOT EXISTS idx_reports_status
    ON public.reports(status);

CREATE INDEX IF NOT EXISTS idx_reports_created_at
    ON public.reports(created_at DESC);

CREATE INDEX IF NOT EXISTS idx_report_history_report_id
    ON public.report_status_history(report_id);

CREATE INDEX IF NOT EXISTS idx_report_history_changed_at
    ON public.report_status_history(changed_at DESC);


-- ============================================================
-- 6. AUTOMATIC PROFILE CREATION
-- Akun baru otomatis mendapatkan role user.
-- Role admin harus diberikan secara terpisah.
-- ============================================================

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    INSERT INTO public.profiles (id, full_name, role)
    VALUES (
        NEW.id,
        NULLIF(NEW.raw_user_meta_data ->> 'full_name', ''),
        'user'
    )
    ON CONFLICT (id) DO NOTHING;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;

CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW
EXECUTE FUNCTION public.handle_new_user();


-- ============================================================
-- 7. CHECK ADMIN ROLE
-- Memeriksa apakah pengguna yang login adalah admin.
-- ============================================================

CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.profiles
        WHERE id = (SELECT auth.uid())
          AND role = 'admin'
    );
$$;

REVOKE ALL ON FUNCTION public.is_admin() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.is_admin() TO authenticated;


-- ============================================================
-- 8. UPDATED_AT TRIGGER
-- Memperbarui waktu perubahan laporan.
-- ============================================================

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS set_reports_updated_at ON public.reports;

CREATE TRIGGER set_reports_updated_at
BEFORE UPDATE ON public.reports
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at();


-- ============================================================
-- 9. ADMIN UPDATE REPORT STATUS
-- Perubahan status hanya melalui fungsi ini.
--
-- Parameter RPC:
-- p_admin_note : TEXT
-- p_report_id  : UUID
-- p_status     : TEXT
--
-- Frontend harus mengirim ketiga parameter tersebut.
-- ============================================================

CREATE OR REPLACE FUNCTION public.admin_update_report_status(
    p_admin_note TEXT,
    p_report_id UUID,
    p_status TEXT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_old_status TEXT;
    v_note TEXT;
BEGIN
    -- Pastikan pengguna sudah login dan merupakan admin.
    IF (SELECT auth.uid()) IS NULL
       OR NOT public.is_admin() THEN
        RAISE EXCEPTION 'Akses ditolak: hanya admin yang dapat mengubah status laporan.';
    END IF;

    -- Validasi status baru.
    IF p_status IS NULL OR p_status NOT IN (
        'pending',
        'reviewing',
        'revision',
        'rejected',
        'forwarded',
        'in_progress',
        'completed'
    ) THEN
        RAISE EXCEPTION 'Status laporan tidak valid.';
    END IF;

    v_note := NULLIF(BTRIM(p_admin_note), '');

    -- Catatan wajib untuk revisi atau penolakan.
    IF p_status IN ('revision', 'rejected')
       AND v_note IS NULL THEN
        RAISE EXCEPTION 'Catatan admin wajib diisi untuk revisi atau penolakan.';
    END IF;

    -- Ambil status lama dan kunci laporan selama proses.
    SELECT status
    INTO v_old_status
    FROM public.reports
    WHERE id = p_report_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Laporan tidak ditemukan.';
    END IF;

    -- Perbarui status dan informasi pemeriksaan.
    UPDATE public.reports
    SET
        status = p_status,
        admin_note = v_note,
        reviewed_by = (SELECT auth.uid()),
        reviewed_at = NOW()
    WHERE id = p_report_id;

    -- Catat perubahan status untuk riwayat.
    INSERT INTO public.report_status_history (
        report_id,
        changed_by,
        old_status,
        new_status,
        note
    )
    VALUES (
        p_report_id,
        (SELECT auth.uid()),
        v_old_status,
        p_status,
        v_note
    );
END;
$$;

REVOKE ALL ON FUNCTION public.admin_update_report_status(TEXT, UUID, TEXT)
    FROM PUBLIC;

GRANT EXECUTE ON FUNCTION public.admin_update_report_status(TEXT, UUID, TEXT)
    TO authenticated;


