-- Pengguna hanya dapat mengunggah foto ke folder dengan nama
-- UUID akun mereka, misalnya: <user-uuid>/foto.jpg.

DROP POLICY IF EXISTS "report_photos_upload_own"
    ON storage.objects;

CREATE POLICY "report_photos_upload_own"
ON storage.objects
FOR INSERT
TO authenticated
WITH CHECK (
    bucket_id = 'report-photos'
    AND (storage.foldername(name))[1] = (SELECT auth.uid())::TEXT
);


-- Pengguna dapat melihat foto milik sendiri.
-- Admin dapat melihat seluruh foto laporan.

DROP POLICY IF EXISTS "report_photos_read_own_or_admin"
    ON storage.objects;

CREATE POLICY "report_photos_read_own_or_admin"
ON storage.objects
FOR SELECT
TO authenticated
USING (
    bucket_id = 'report-photos'
    AND (
        (storage.foldername(name))[1] = (SELECT auth.uid())::TEXT
        OR public.is_admin()
    )
);


-- Pengguna dapat menghapus foto milik sendiri.
-- Admin dapat menghapus foto laporan.

DROP POLICY IF EXISTS "report_photos_delete_own_or_admin"
    ON storage.objects;

CREATE POLICY "report_photos_delete_own_or_admin"
ON storage.objects
FOR DELETE
TO authenticated
USING (
    bucket_id = 'report-photos'
    AND (
        (storage.foldername(name))[1] = (SELECT auth.uid())::TEXT
        OR public.is_admin()
    )
);


