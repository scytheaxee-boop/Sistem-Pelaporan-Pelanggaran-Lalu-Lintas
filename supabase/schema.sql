-- ------------------------------------------------------------
-- PROFILES POLICIES
-- Pengguna dapat membaca profil sendiri.
-- Admin dapat membaca seluruh profil.
-- ------------------------------------------------------------

DROP POLICY IF EXISTS "profiles_select_own_or_admin"
    ON public.profiles;

CREATE POLICY "profiles_select_own_or_admin"
ON public.profiles
FOR SELECT
TO authenticated
USING (
    id = (SELECT auth.uid())
    OR public.is_admin()
);


-- ------------------------------------------------------------
-- REPORTS POLICIES
-- Pengguna dapat membaca laporan miliknya.
-- Admin dapat membaca semua laporan.
-- Pengguna dapat membuat laporan atas nama sendiri.
-- ------------------------------------------------------------

DROP POLICY IF EXISTS "reports_select_own_or_admin"
    ON public.reports;

CREATE POLICY "reports_select_own_or_admin"
ON public.reports
FOR SELECT
TO authenticated
USING (
    user_id = (SELECT auth.uid())
    OR public.is_admin()
);


DROP POLICY IF EXISTS "reports_insert_own"
    ON public.reports;

CREATE POLICY "reports_insert_own"
ON public.reports
FOR INSERT
TO authenticated
WITH CHECK (
    user_id = (SELECT auth.uid())
    AND status = 'pending'
    AND admin_note IS NULL
    AND reviewed_by IS NULL
    AND reviewed_at IS NULL
);


-- ------------------------------------------------------------
-- REPORT STATUS HISTORY POLICIES
-- Pengguna dapat membaca riwayat laporan miliknya.
-- Admin dapat membaca semua riwayat.
-- Penulisan riwayat dilakukan melalui fungsi admin.
-- ------------------------------------------------------------

DROP POLICY IF EXISTS "history_select_own_or_admin"
    ON public.report_status_history;

CREATE POLICY "history_select_own_or_admin"
ON public.report_status_history
FOR SELECT
TO authenticated
USING (
    public.is_admin()
    OR EXISTS (
        SELECT 1
        FROM public.reports r
        WHERE r.id = report_id
          AND r.user_id = (SELECT auth.uid())
    )
);


